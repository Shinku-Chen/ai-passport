#!/usr/bin/env python3
"""Generate tests/fixtures/clannad_paths.h from the source checkout.

The two-policy chapter sweep in the C VM covers 98 of the 105 termination sites
that the source exploration finds. This tool re-runs the same independent
interpreter, keeps one explicit choice path for each extra site, and writes a
small C fixture. It does not import the packer.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import clannad_audit as A


def replay(src, start, story, path, progress):
    walker = A.Walker(src)
    state = A.State(start, story)
    if progress:
        for bit in A.AFTER_FLAGS:
            state.variables[f"g:{bit}"] = 1
        state.variables["g:0"] = 13
        state.variables["g:45"] = 1
    fnv = 1469598103934665603

    def mix(data):
        nonlocal fnv
        for byte in data:
            fnv ^= byte
            fnv = (fnv * 1099511628211) & 0xFFFFFFFFFFFFFFFF

    texts = choices = 0
    used = 0
    for _ in range(400000):
        frame = walker.interp.read_frame(state)
        if frame["type"] == "text":
            texts += 1
            mix(b"T")
            mix((frame["speaker"] or "").encode())
            mix(b"\x00")
            mix((frame["text"] or "").encode())
            mix(b"\x00")
            walker.interp.next(state)
        elif frame["type"] == "choice":
            if used >= len(path):
                raise SystemExit("path exhausted")
            index = path[used]
            used += 1
            choices += 1
            mix(b"C")
            for item in frame["items"]:
                mix(A.js_str(item["text"]).encode())
                mix(b"\x01")
            walker.interp.choose(state, frame["items"][index], index)
        elif frame["type"] == "end":
            return state.chapter, state.cursor, texts, choices, fnv
        elif frame["type"] in ("jump", "yield"):
            continue
    raise SystemExit("path did not end")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", default="tests/fixtures/clannad_paths.h")
    args = ap.parse_args()
    src = A.load_source(args.source)
    walker = A.Walker(src)

    sweep_sites = set()
    for chapter in [c["id"] for c in src.catalog["chapters"]]:
        for policy in (A.first_policy, A.last_policy):
            state = A.State(chapter, False)
            outcome = walker.run(state, policy, max_ops=400000)
            if outcome["stop"] == "end":
                sweep_sites.add((state.chapter, state.cursor))

    rows = []
    for chapter in [c["id"] for c in src.catalog["chapters"]]:
        ends, _states, _visited = A.explore_from(src, chapter, False, 200000)
        for (scene, op), path in ends.items():
            if (scene, op) in sweep_sites:
                continue
            indices = [entry[2] for entry in path]
            end = replay(src, chapter, False, indices, False)
            if (end[0], end[1]) != (scene, op):
                raise SystemExit(f"path replay mismatch {chapter} {scene}:{op}")
            rows.append((chapter, 0, 0, indices, *end))
            sweep_sites.add((scene, op))

    # After Story / true-ending progress path if exploration finds one outside
    # the chapter sweep. (This script keeps the option; the current source's
    # 7200:1340 site is already reached by the chapter sweep.)
    for target, indices in ():
        pass

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by tools/clannad_paths.py; do not edit.\n")
        fh.write("// Explicit choice paths for termination sites not reached by the\n")
        fh.write("// two-policy sweep.\n")
        fh.write("#pragma once\n#include <stdint.h>\n\n")
        fh.write("typedef struct {\n    uint16_t start;\n    uint8_t story;\n"
                 "    uint8_t progress;\n    uint8_t path_len;\n    uint8_t path[32];\n"
                 "    uint16_t end_scene;\n    uint16_t end_op;\n    uint32_t texts;\n"
                 "    uint32_t choices;\n    uint64_t fnv;\n} clannad_path_fixture_t;\n\n")
        fh.write("static const clannad_path_fixture_t CLANNAD_PATHS[] = {\n")
        for start, story, progress, path, es, eo, texts, choices, fnv in rows:
            padded = path + [0] * (32 - len(path))
            fh.write("    {%u, %u, %u, %u, {%s}, %u, %u, %u, %u, 0x%016xULL},\n" % (
                start, story, progress, len(path),
                ", ".join(str(x) for x in padded), es, eo, texts, choices, fnv))
        fh.write("};\n\n#define CLANNAD_PATH_COUNT %u\n" % len(rows))
    print(f"wrote {out} ({len(rows)} paths)")


if __name__ == "__main__":
    main()
