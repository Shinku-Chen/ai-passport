#!/usr/bin/env python3
"""Compile the pinned RW5 runtime data into the GalGame content layer.

No original-game extraction is required. Story control flow stays independent
of LVGL; JPEG scenes are precomposited so LVGL can stream MCUs from flash.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIN = '76bba0bb0bfcc066ce6a35883d76c5b19981e0cb'

def quote(s):
    return json.dumps(s, ensure_ascii=False)

def load(source):
    raw = (source / 'src/common/catalog.js').read_text(encoding='utf-8')
    catalog = json.loads(raw[raw.index('{'):].strip().rstrip(';'))
    scenes = catalog['scenes']
    ops = {s['id']: json.loads((source / 'src/common/story' / s['file']).read_text(encoding='utf-8')) for s in scenes}
    return catalog, ops

def compile_content(source, quality=24):
    from PIL import Image, ImageOps
    cat, ops = load(source)
    scenes = cat['scenes']
    chapter_ids = [s['id'] for s in scenes if s['id'] == s['chapterKey']]
    chapter_map = {s: i for i, s in enumerate(chapter_ids)}
    var_names = sorted({x['key'] for s in scenes for x in (s.get('onExit') or [])} |
                       {x['key'] for os in ops.values() for o in os for it in o.get('items', []) for x in it.get('changes', [])})
    assert len(var_names) <= 8
    var_index = {v: i for i, v in enumerate(var_names)}
    out = ['/* Generated by tools/yakata_import.py; do not edit. */', '#include "gal_content.h"', '#include "yakata_flow.h"', '#include "lvgl.h"', '#include <string.h>']
    flow = ['/* Generated, pure story graph. */', '#include "yakata_flow.h"', '#include <string.h>']
    image_defs, image_cache, payload = [], {}, bytearray()
    asset_cache = {}
    encoded_cache = {}
    def image_file(a):
        if a not in asset_cache:
            path = source / 'src' / cat['assets'][a].lstrip('/')
            asset_cache[a] = Image.open(path).convert('RGBA')
        return asset_cache[a]
    def add_image(key, image):
        if key in image_cache:
            return image_cache[key]
        bio = io.BytesIO()
        image.convert('RGB').save(bio, format='JPEG', quality=quality, optimize=True, progressive=False, subsampling=2)
        data = bio.getvalue()
        digest = hashlib.sha256(data).digest()
        if digest in encoded_cache:
            image_cache[key] = encoded_cache[digest]
            return image_cache[key]
        i = len(image_defs)
        offset = len(payload)
        payload.extend(data)
        while len(payload) % 4: payload.append(0)
        image_defs.append(f'static const lv_image_dsc_t img_{i} = {{ .header = {{ .magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_RAW, .w={image.width}, .h={image.height} }}, .data_size={len(data)}, .data=yakata_art_start+{offset} }};')
        image_cache[key] = f'&img_{i}'
        encoded_cache[digest] = image_cache[key]
        return image_cache[key]
    def scene_image(o):
        key = ('frame', o.get('background'), o.get('portrait'), o.get('pw',320), o.get('ph',254))
        if key in image_cache: return image_cache[key]
        # Scale the 432px RW5 stage to 320px; retain the complete 16:9
        # background. Sprites share the original stage-relative baseline.
        # The translucent 90px dialogue panel overlays the lower art.
        im = Image.new('RGB', (320,240), '#090b10')
        bg = o.get('background')
        if bg:
            im.paste(image_file(bg).convert('RGB').resize((320,180), Image.Resampling.LANCZOS), (0,0))
        body = o.get('portrait')
        if body:
            w = max(1, round(o.get('pw',320)*320/432))
            h = max(1, round(o.get('ph',254)*320/432))
            sprite = image_file(body).resize((w,h), Image.Resampling.LANCZOS)
            im.paste(sprite, ((320-w)//2,196-h), sprite)
        return add_image(key,im)
    title = ImageOps.fit(image_file('title').convert('RGB'), (320,240), method=Image.Resampling.LANCZOS)
    title_image = add_image(('title',),title)
    events, lines, choices, transitions, endings = [], [], [], [], []
    event_chapters, event_cgs, starts, positions = [], [], {}, {}
    cg_by_asset = {a: i for i,g in enumerate(cat['gallery']) for a in g['variants']}
    cg_first = [65535]*len(cat['gallery'])
    def event(kind,index,ch,cg=255):
        n=len(events); events.append((kind,index));event_chapters.append(ch);event_cgs.append(cg)
        if cg != 255 and cg_first[cg] == 65535: cg_first[cg]=n
        return n
    for s in scenes:
        sid=s['id']; ch=chapter_map[s['chapterKey']];starts[sid]=len(events)
        if s['id'] == s['chapterKey']:
            event('GAL_EV_TRANSITION',len(transitions),ch)
            transitions.append((s['name'], 'SHINUYAKATA', s['name'], '死馆 · 离线阅读'))
        for cursor,o in enumerate(ops[sid]):
            positions[sid,cursor]=len(events)
            if o['type']=='text':
                event('GAL_EV_LINE',len(lines),ch,cg_by_asset.get(o.get('background'),255))
                lines.append((o.get('speaker',''),o['text'],scene_image(o)))
            elif o['type']=='choice':
                event('GAL_EV_CHOICE',len(choices),ch)
                choices.append((sid,o))
            else: raise ValueError(f'unsupported op {o["type"]}')
        if s.get('next') or s.get('routes'):
            event('GAL_EV_FLOW',scenes.index(s),ch)
        else:
            event('GAL_EV_ENDING',len(endings),ch)
            endings.append(('SOURCE EXIT',s['name'],s.get('ending') or '源移植版此处结束。'))
    assert len(events)<65535 and len(lines)<65535
    def changes(items):
        return ''.join(f'v[{var_index[x["key"]]}] {"+=" if "add" in x else "="} {int(x.get("add",x.get("value",0)))};' for x in items or [])
    def condition(c):
        if not c: return '1'
        if 'all' in c: return '('+' && '.join(condition(x) for x in c['all'])+')'
        return f'v[{var_index[c["key"]]}] == {int(c["equals"])}' if 'equals' in c else f'v[{var_index[c["key"]]}] != 0'
    out += ['extern const uint8_t yakata_art_start[] __asm__("_binary_yakata_art_bin_start");']+image_defs
    out += [f'const void *gal_content_title_image={title_image};', 'const gal_line_t gal_content_lines[]={']
    out += [f'{{{quote(n)},{quote(t)},GAL_UNLOCK_NONE,{im},0}},' for n,t,im in lines]
    out += ['};',f'const int gal_content_line_count={len(lines)};']
    for i,(_,o) in enumerate(choices):
        out += [f'static const gal_option_t options_{i}[]={{']+[f'{{{quote(it["text"])},GAL_UNLOCK_NONE,GAL_UNLOCK_NONE}},' for it in o['items']]+['};']
    out += ['const gal_choice_t gal_content_choices[]={']+[f'{{"请选择",{len(o["items"])},options_{i}}},' for i,(_,o) in enumerate(choices)]+['};',f'const int gal_content_choice_count={len(choices)};']
    out += ['const gal_event_t gal_content_events[]={']+[f'{{{k},{i},GAL_UNLOCK_NONE}},' for k,i in events]+['};',f'const int gal_content_event_count={len(events)};']
    def table(name,typ,rows):
        nonlocal out
        out += [f'const {typ} gal_content_{name}[]={{']+['{'+','.join(quote(v) for v in row)+'},' for row in rows]+['};',f'const int gal_content_{name[:-1]}_count={len(rows)};']
    table('transitions','gal_transition_t',transitions)
    table('endings','gal_ending_t',endings)
    # All 311 variants remain browsable within their original 56 groups.
    cg_images, cg_offsets, thumbs = [], [0], []
    for g in cat['gallery']:
        for a in g['variants']:
            cg_images.append(scene_image(dict(background=a,portrait='',pw=320,ph=254)))
        cg_offsets.append(len(cg_images))
        thumbs.append(add_image(('thumb',g['id']),ImageOps.fit(image_file(g['variants'][0]).convert('RGB'),(64,40),method=Image.Resampling.LANCZOS)))
    # Images added above must precede the tables that reference them.
    split=out.index(f'const void *gal_content_title_image={title_image};')
    out[split:split]=image_defs[sum(x.startswith('static const lv_image_dsc_t') for x in out):]
    out += ['const gal_cg_t gal_content_cgs[]={']+[f'{{{quote(g["name"])},{quote(g["name"])},{cg_first[i]},{thumbs[i]},false}},' for i,g in enumerate(cat['gallery'])]+['};',f'const int gal_content_cg_count={len(thumbs)};']
    out += ['const void *const yakata_cg_images[]={'+','.join(cg_images)+'};', 'const uint16_t yakata_cg_offsets[]={'+','.join(map(str,cg_offsets))+'};']
    out += ['const gal_chapter_t gal_content_chapters[]={']+[f'{{{quote(s["name"])},"", "", {starts[s["id"]]},GAL_UNLOCK_NONE,false}},' for s in scenes if s['id'] == s['chapterKey']]+['};',f'const int gal_content_chapter_count={len(chapter_ids)};']
    out += ['const gal_recall_t gal_content_recalls[]={']+[f'{{{quote(g["name"])},{quote(transitions[event_chapters[cg_first[i]]][0]) if cg_first[i]!=65535 else quote("")},{i},{cg_first[i] if cg_first[i]!=65535 else 0}}},' for i,g in enumerate(cat['gallery'])]+['};',f'const int gal_content_recall_count={len(thumbs)};']
    out += ['const gal_track_t gal_content_tracks[1]={{0}};', 'const int gal_content_track_count=0;',
            'const gal_about_row_t gal_content_about_rows[]={{"版本",GAL_CONTENT_VERSION},{"源移植", "xuanyide / RW5 0.3.7"},{"原作", "BUG SYSTEM"},{"适配", "Shinku-Chen / Cindy"}};', 'const int gal_content_about_row_count=4;',
            'const char *const gal_content_title_menu[]={"开始游戏","继续游戏","读取存档","设置","鉴赏室","关于"};', 'const int gal_content_title_menu_count=6;',
            'const char *const gal_content_quick_menu[]={"返回剧情","保存进度","读取存档","历史文本","设置","返回标题"};', 'const int gal_content_quick_menu_count=6;',
            'const char *const gal_content_gallery_menu[]={"CG 鉴赏","CG 回想","章节选择","音乐（源版未提供）"};','const int gal_content_gallery_menu_count=4;']
    flow += [f'const uint8_t yakata_event_chapters[]={{'+','.join(map(str,event_chapters))+'};',f'const uint8_t yakata_event_cgs[]={{'+','.join(map(str,event_cgs))+'};', 'const uint16_t yakata_chapter_events[]={'+','.join(str(starts[x]) for x in chapter_ids)+'};']
    flow += ['int yakata_exit(int scene, int32_t v[YAKATA_VAR_COUNT]) { switch(scene) {']
    for i,s in enumerate(scenes):
        flow += [f'case {i}: {changes(s.get("onExit"))}'.rstrip()]
        if s.get('routes'):
            flow += [f'if ({condition(r["when"])}) return {starts[r["target"]]};' for r in s['routes']]
            flow += ['return -1;']
        elif s.get('next'): flow += [f'return {starts[s["next"]]};']
        else: flow += ['return -1;']
    flow += ['default:return -1; }}', 'int yakata_choose(int choice,int option,int32_t v[YAKATA_VAR_COUNT]) { switch(choice) {']
    for i,(_,o) in enumerate(choices):
        flow += [f'case {i}: switch(option) {{']+[f'case {j}: {changes(it.get("changes"))} return {starts[it["scene"]]};' for j,it in enumerate(o['items'])]+['default:return -1;}']
    flow += ['default:return -1;}}']
    data=ROOT/'main/yakata_data';data.mkdir(exist_ok=True)
    (data/'yakata_art.bin').write_bytes(payload)
    (ROOT/'main/gal/gal_content.c').write_text('\n'.join(out)+'\n',encoding='utf-8')
    (ROOT/'main/gal/yakata_flow.c').write_text('\n'.join(flow)+'\n',encoding='utf-8')
    report=dict(source_commit=PIN, scenes=len(scenes),chapters=len(chapter_ids),lines=len(lines),choices=len(choices),events=len(events),cg_groups=len(thumbs),cg_variants=len(cg_images),jpeg_images=len(image_defs),jpeg_bytes=len(payload),variables=var_names,source_exits=[s['id'] for s in scenes if not s.get('next') and not s.get('routes')],quality=quality,screen=[320,240],background=[320,180],sprite_baseline=196,thumbnail=[64,40])
    (data/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,ensure_ascii=False))

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--source',type=Path,default=ROOT/'assets/yakata-source');ap.add_argument('--quality',type=int,default=24)
    a=ap.parse_args();compile_content(a.source,a.quality)
