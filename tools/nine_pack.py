#!/usr/bin/env python3
"""Read-only pinned-source -> AI Passport pack for 9-nine- 天色天歌天籁音.

The authoritative input is the already-converted Watch graph (graph.js) plus
its committed text chunks.  This script never runs the PC-game preprocessing
scripts and never writes into the source checkout.

    python tools/nine_pack.py --source <9-nine-rw5 checkout> \
        --out assets/nine --expect-commit 6a8907a5ae576f4377abe4b74f15bd9af13efe07

Outputs (into --out):
    nine_script.bin        graph/text/variable/chapter/ending/gallery IR
    nine_images.bin        JPEG backgrounds + indexed sprites/faces + OP frames
    nine_symbols.txt       every character used by story, graph metadata and UI
    nine_pack_report.json  counts, hashes, source digest, media inventory

The pack header carries the SHA-256 of the pinned graph, every chunk file,
gallery/opening metadata and every media file referenced by the pack.  The
reader re-checks it, so a report generated by this tool is never the evidence.
"""
from __future__ import annotations

import argparse
import array
import hashlib
import io
import json
import math
import struct
import subprocess
import sys
import zlib
from pathlib import Path

from PIL import Image, ImageOps

NONE = 0xFFFFFFFF
COND = {"==": 1, "!=": 2, "<": 3, "<=": 4, ">": 5, ">=": 6}
SOURCE_STAGE = (432, 243)
ART_SIZE = (240, 135)
TITLE_CROP = (0, 80, 432, 323)  # 432x243 (16:9) centre of the 432x514 key visual
TITLE_BG_SIZE = (240, 135)
PACK_VERSION = 2


def die(message: str) -> "None":
    raise SystemExit("nine_pack: " + message)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def crc32(data: bytes) -> int:
    return zlib.crc32(data) & NONE


def p32(*values: int) -> bytes:
    return struct.pack("<" + "I" * len(values), *(x & NONE for x in values))


def js_graph(path: Path) -> dict:
    text = path.read_text("utf-8").strip()
    prefix = "export const GRAPH = "
    if not text.startswith(prefix):
        die(f"unexpected graph.js shape: {path}")
    text = text[len(prefix):].strip()
    if text.endswith(";"):
        text = text[:-1]
    return json.loads(text)


class Strings:
    def __init__(self) -> None:
        self.data = bytearray(b"\0")
        self.offsets = {"": 0}
        self.chars: set[str] = set()

    def add(self, value: object) -> int:
        text = str(value or "")
        self.chars.update(text)
        if text not in self.offsets:
            self.offsets[text] = len(self.data)
            self.data.extend(text.encode("utf-8") + b"\0")
        return self.offsets[text]


class Media:
    def __init__(self, source: Path, quality: int, op_fps: float, audio_rate: int) -> None:
        self.source = source
        self.quality = quality
        self.op_fps = op_fps
        self.audio_rate = audio_rate
        self.images: list[dict] = []
        self.keys: dict[tuple, int] = {}
        self.ops: list[tuple[int, int, int]] = []
        self.audio: list[tuple[int, int, bytes, int, int, int]] = []
        self.meta: list[dict] = []
        self.read_paths: set[str] = set()

    def _read_bytes(self, rel: str) -> bytes:
        path = self.source / rel
        if not path.is_file():
            die(f"missing source media: {rel}")
        self.read_paths.add(rel)
        return path.read_bytes()

    def image(self, rel: str | None, crop: tuple[int, int, int, int] | None = None,
              sprite: bool = False, size: tuple[int, int] | None = None,
              opaque: bool = False) -> int:
        if not rel:
            return NONE
        key = (rel, crop, sprite, size, opaque)
        if key in self.keys:
            return self.keys[key]
        rel = rel.lstrip("/")
        path = self.source / "src" / rel
        if not path.is_file():
            die(f"missing source image: {rel}")
        self.read_paths.add("src/" + rel)
        with Image.open(path) as image:
            image = image.convert("RGBA" if sprite else "RGB")
            if crop:
                image = image.crop(crop)
            if size is None:
                size = (max(1, round(image.width * ART_SIZE[0] / SOURCE_STAGE[0])),
                        max(1, round(image.height * ART_SIZE[1] / SOURCE_STAGE[1]))) if sprite else ART_SIZE
            if not sprite and abs(image.width / image.height - size[0] / size[1]) > 0.03:
                scaled = ImageOps.contain(image, size, Image.Resampling.LANCZOS)
                canvas = Image.new("RGB", size)
                canvas.paste(scaled, ((size[0] - scaled.width) // 2, (size[1] - scaled.height) // 2))
                image = canvas
            else:
                image = image.resize(size, Image.Resampling.LANCZOS)
            if sprite:
                palette_image = image.quantize(colors=192, method=Image.Quantize.FASTOCTREE)
                rgba = palette_image.convert("RGBA")
                colors = rgba.getcolors(maxcolors=256)
                if not colors:
                    die(f"indexed image exceeds 256 colours: {rel}")
                palette = sorted(color for _, color in colors)
                index = {color: i for i, color in enumerate(palette)}
                raw = bytes(index[color] for color in rgba.getdata())
                blocks = [zlib.compress(raw[y * image.width:min(image.height, y + 8) * image.width], 9)
                          for y in range(0, image.height, 8)]
                record = {"kind": 1, "w": image.width, "h": image.height,
                          "palette": b"".join(bytes(color) for color in palette),
                          "blocks": blocks, "crc": crc32(raw)}
            else:
                buffer = io.BytesIO()
                image.save(buffer, "JPEG", quality=self.quality, optimize=True,
                           progressive=False, subsampling=2)
                payload = buffer.getvalue()
                record = {"kind": 0, "w": image.width, "h": image.height,
                          "data": payload, "crc": crc32(payload)}
        # Bind each packed image to the exact source/crop/size request. The
        # reader ignores this tag; the independent audit recomputes it from the
        # source and refuses a stale or swapped image.
        tag = crc32(f"{rel}|{crop}|{sprite}|{size}|{opaque}".encode())
        record["tag"] = tag
        asset = len(self.images)
        self.keys[key] = asset
        self.images.append(record)
        self.meta.append({"id": asset, "source": "/" + rel, "crop": crop,
                          "sprite": sprite, "size": list(size),
                          "kind": "indexed" if sprite else "jpeg", "tag": f"{tag:08x}",
                          "bytes": len(record.get("data", b"")) + sum(map(len, record.get("blocks", [])))})
        return asset

    def add_opening(self) -> dict:
        rel = "converted/opening/timeline.json"
        path = self.source / rel
        if not path.is_file():
            die("missing converted/opening/timeline.json")
        self.read_paths.add(rel)
        timeline = json.loads(path.read_text("utf-8"))
        duration = timeline["durationMs"]
        frames = timeline["frames"]
        picked: list[dict] = []
        seen: set[int] = set()
        for i in range(math.ceil(duration * self.op_fps / 1000)):
            index = min(len(frames) - 1, round(i * timeline["fps"] / self.op_fps))
            if index not in seen:
                picked.append(frames[index])
                seen.add(index)
        if picked[-1] is not frames[-1]:
            picked.append(frames[-1])
        for i, frame in enumerate(picked):
            end = picked[i + 1]["atMs"] if i + 1 < len(picked) else duration
            self.ops.append((self.image(frame["src"]), int(frame["atMs"]), int(end - frame["atMs"])))
        return {"sourceFrames": len(frames), "sourceFps": timeline["fps"],
                "outputFrames": len(picked), "targetFps": self.op_fps,
                "durationMs": duration, "firstAtMs": int(picked[0]["atMs"]),
                "lastAtMs": int(picked[-1]["atMs"])}

    def add_audio(self, strings: Strings) -> list[dict]:
        try:
            import imageio_ffmpeg
            ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
        except ImportError:
            ffmpeg = "ffmpeg"
        report = []
        for name in ("title", "opening"):
            rel = f"src/common/{name}-bgm.opus"
            source = self.source / rel
            if not source.is_file():
                die(f"missing source audio: {rel}")
            self.read_paths.add(rel)
            result = subprocess.run(
                [ffmpeg, "-v", "error", "-i", str(source), "-f", "s16le",
                 "-ac", "1", "-ar", str(self.audio_rate), "-"],
                capture_output=True, check=True)
            samples = array.array("h")
            samples.frombytes(result.stdout)
            if sys.byteorder != "little":
                samples.byteswap()
            data = ima_encode(samples)
            duration = round(len(samples) * 1000 / self.audio_rate)
            self.audio.append((1, strings.add(name), data, duration, self.audio_rate, 1))
            report.append({"name": name, "durationMs": duration, "bytes": len(data),
                           "sampleRate": self.audio_rate, "channels": 1,
                           "codec": "IMA ADPCM", "source": rel})
        return report

    def serialize(self, title: tuple[int, int], title_logo: int) -> bytes:
        image_off = 128
        op_off = image_off + 32 * len(self.images)
        audio_off = op_off + 12 * len(self.ops)
        blob = bytearray(audio_off + 32 * len(self.audio))
        records = []
        for image in self.images:
            off = len(blob)
            if image["kind"] == 0:
                blob.extend(image["data"])
            else:
                blocks = image["blocks"]
                palette = image["palette"]
                blob.extend(p32(len(palette) // 4, 8, len(blocks)))
                blob.extend(palette)
                table = len(blob)
                blob.extend(b"\0" * (8 * len(blocks)))
                for i, block in enumerate(blocks):
                    struct.pack_into("<II", blob, table + i * 8, len(blob), len(block))
                    blob.extend(block)
            records.append((image["kind"], image["w"], image["h"], off,
                            len(blob) - off, image["crc"], image.get("tag", 0), 0))
        for i, record in enumerate(records):
            struct.pack_into("<8I", blob, image_off + i * 32, *record)
        for i, record in enumerate(self.ops):
            struct.pack_into("<3I", blob, op_off + i * 12, *record)
        for i, (kind, name, data, duration, rate, channels) in enumerate(self.audio):
            off = len(blob)
            blob.extend(data)
            struct.pack_into("<8I", blob, audio_off + i * 32, kind, name, off,
                             len(data), duration, rate, channels, crc32(data))
        fields = [PACK_VERSION, len(blob), 0, len(self.images), image_off,
                  len(self.ops), op_off, len(self.audio), audio_off, *title, title_logo]
        blob[:8] = b"NINEIM1\0"
        struct.pack_into("<" + "I" * len(fields), blob, 8, *fields)
        struct.pack_into("<I", blob, 16, crc32(blob))
        return bytes(blob)


IMA_STEPS = (7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37,
             41, 45, 50, 55, 60, 66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173,
             190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658,
             724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066,
             2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894,
             6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289,
             16818, 18500, 20350, 22385, 24623, 27086, 29794, 32767)
IMA_INDEX = (-1, -1, -1, -1, 2, 4, 6, 8)


def ima_encode(samples: array.array) -> bytes:
    result = bytearray()
    index = 0
    for pos in range(0, len(samples), 256):
        chunk = list(samples[pos:pos + 256])
        chunk.extend([chunk[-1]] * (256 - len(chunk)))
        predictor = chunk[0]
        result.extend(struct.pack("<hBB", predictor, index, 0))
        nibbles = []
        for value in chunk[1:]:
            step = IMA_STEPS[index]
            delta = value - predictor
            code = 8 if delta < 0 else 0
            delta = abs(delta)
            difference = step >> 3
            for bit, threshold in ((4, step), (2, step >> 1), (1, step >> 2)):
                if delta >= threshold:
                    code |= bit
                    delta -= threshold
                    difference += threshold
            predictor = max(-32768, min(32767, predictor + (-difference if code & 8 else difference)))
            index = max(0, min(88, index + IMA_INDEX[code & 7]))
            nibbles.append(code)
        nibbles.append(0)
        result.extend(nibbles[i] | nibbles[i + 1] << 4 for i in range(0, 256, 2))
    return bytes(result)


def pack(source_root: Path, out: Path, quality: int, op_fps: float,
         audio_rate: int, expect_commit: str) -> dict:
    source = source_root / "nine-sorairo-rw5" if (source_root / "nine-sorairo-rw5").is_dir() else source_root
    if not (source / "src/common/graph.js").is_file():
        die(f"not a nine-sorairo source checkout: {source}")
    try:
        commit = subprocess.check_output(
            ["git", "-C", str(source_root), "rev-parse", "HEAD"], text=True).strip()
    except subprocess.CalledProcessError:
        die("source must be a pinned Git checkout")
    if expect_commit and commit != expect_commit:
        die(f"source commit {commit} != expected {expect_commit}")

    graph = js_graph(source / "src/common/graph.js")
    declared = json.loads((source / "converted/graph.json").read_text("utf-8"))
    if len(graph["nodes"]) != len(declared["nodes"]):
        die("graph.js and converted/graph.json node counts differ")
    for key, node in graph["nodes"].items():
        old = declared["nodes"].get(key)
        if old is None:
            die(f"converted graph is missing node {key}")
        for field in ("title", "chapter", "count", "ops", "effects", "nexts",
                      "choices", "complete"):
            if node.get(field, [] if field in ("ops", "effects", "nexts", "choices", "complete") else None) != \
                    old.get(field, [] if field in ("ops", "effects", "nexts", "choices", "complete") else None):
                die(f"graph.js and converted/graph.json differ at {key}.{field}")
        # graph.js is the runtime authority; converted/graph.json additionally
        # keeps the original script/label names used for source reconciliation.
        node.setdefault("script", old.get("script", ""))
        node.setdefault("label", old.get("label", ""))
    if declared.get("start") != graph.get("start") or declared.get("endings") != graph.get("endings"):
        die("graph start/endings differ between graph.js and converted/graph.json")

    engine = (source / "src/common/engine.js").read_text("utf-8")
    persistent = set()
    body = engine.split("const PERSISTENT_KEYS =", 1)[1].split("};", 1)[0]
    for line in body.splitlines():
        if ":" in line and "true" in line:
            persistent.add(line.split(":", 1)[0].strip())
    persistent.add("loop1")
    for ending in graph.get("endings", []):
        persistent.add(ending["id"])

    strings = Strings()
    media = Media(source, quality, op_fps, audio_rate)
    source_files: list[str] = [
        "src/common/graph.js", "src/common/engine.js", "src/common/chunk-codec.js",
        "converted/graph.json", "converted/gallery.json", "converted/opening/timeline.json",
    ]
    for rel in source_files:
        if not (source / rel).is_file():
            die(f"missing source metadata: {rel}")

    source_sha = commit
    episode = strings.add("sorairo")
    title_text = json.loads((source / "src/manifest.json").read_text("utf-8"))["name"]
    title_s = strings.add(title_text)
    sha_s = strings.add(source_sha)
    nodes = list(graph["nodes"])
    node_index = {name: i for i, name in enumerate(nodes)}
    var_names: list[str] = []

    def var(name: str) -> int:
        if name not in var_names:
            var_names.append(name)
            if len(var_names) > 128:
                die("more than 128 source variables")
        return var_names.index(name)

    for name in sorted(persistent):
        var(name)

    conditions: list[tuple[int, int, int]] = []
    effects: list[tuple[int, int, int]] = []
    edges: list[tuple[int, int, int, int, int, int]] = []
    frames: list[tuple[int, int, int, int, int, int]] = []
    visuals: list[tuple[int, int]] = []
    layers: list[tuple[int, int, int, int, int, int]] = []
    visual_map: dict[str, int] = {}
    blocks: list[bytes] = []
    block = bytearray()
    text_raw = 0
    total_text_frames = 0
    op_frames = 0

    def condition(when: list | None) -> None:
        if not when:
            return
        if when[0] == "all":
            for item in when[1:]:
                condition(item)
            conditions.append((7, 0, len(when) - 1))
        else:
            conditions.append((COND[when[1]], var(when[0]), int(when[2])))

    def effect(items: list) -> None:
        for key, op, value in items:
            effects.append((0 if op == "=" else 1, var(key), int(value)))

    def edge(item: dict) -> None:
        first_condition = len(conditions)
        condition(item.get("when"))
        first_effect = len(effects)
        effect(item.get("effects", []))
        edges.append((node_index[item["to"]] if item["to"] != "@end" else NONE,
                      first_condition, len(conditions) - first_condition,
                      first_effect, len(effects) - first_effect,
                      strings.add(item.get("text", ""))))

    def text(value: str) -> tuple[int, int, int]:
        nonlocal text_raw
        payload = value.encode("utf-8")
        strings.chars.update(value)
        text_raw += len(payload)
        if len(payload) + 1 > 8192:
            die("one frame exceeds the 8192-byte text block")
        if len(block) + len(payload) + 1 > 8192:
            blocks.append(bytes(block))
            block.clear()
        position = (len(blocks), len(block), len(payload))
        block.extend(payload + b"\0")
        return position

    def visual(background: str, sprites: list) -> int:
        key = json.dumps([background, sprites], ensure_ascii=False, separators=(",", ":"))
        if key in visual_map:
            return visual_map[key]
        first = len(layers)
        if background:
            layers.append((media.image(background), 0, 0, *ART_SIZE, 255))
        for sprite in sprites:
            if isinstance(sprite, list):
                body_src, width, left = sprite[:3]
                opacity = sprite[3] if len(sprite) > 3 and sprite[3] is not None else 1
                patch = sprite[4] if len(sprite) > 4 else None
                height = sprite[13] if len(sprite) > 13 and sprite[13] else 243
                top = 4 if height >= 200 else 243 - height
                item = {"src": body_src, "width": width, "left": left,
                        "height": height, "top": top, "opacity": opacity}
                if patch:
                    for name, value in zip(
                            ("patch", "patchWidth", "patchHeight", "patchLeft", "patchTop",
                             "patchAtlasWidth", "patchAtlasHeight", "patchImageLeft",
                             "patchImageTop"), sprite[4:13]):
                        item[name] = value
            else:
                item = sprite
            width = max(1, round(item["width"] * ART_SIZE[0] / SOURCE_STAGE[0]))
            height = max(1, round(item.get("height", 243) * ART_SIZE[1] / SOURCE_STAGE[1]))
            x = round(item["left"] * ART_SIZE[0] / SOURCE_STAGE[0])
            y = round(item.get("top", 4) * ART_SIZE[1] / SOURCE_STAGE[1])
            alpha = round(item.get("opacity", 1) * 255)
            layers.append((media.image(item["src"], sprite=True, size=(width, height)),
                           x, y, width, height, alpha))
            if item.get("patch"):
                with Image.open(source / "src" / item["patch"].lstrip("/")) as atlas:
                    atlas_w, atlas_h = atlas.size
                ax = item["patchAtlasWidth"]
                ay = item["patchAtlasHeight"]
                px = -item["patchImageLeft"]
                py = -item["patchImageTop"]
                pw = item["patchWidth"]
                ph = item["patchHeight"]
                crop = (round(px * atlas_w / ax), round(py * atlas_h / ay),
                        round((px + pw) * atlas_w / ax), round((py + ph) * atlas_h / ay))
                patch_size = (max(1, round(pw * ART_SIZE[0] / SOURCE_STAGE[0])),
                              max(1, round(ph * ART_SIZE[1] / SOURCE_STAGE[1])))
                layers.append((media.image(item["patch"], crop=crop, sprite=True, size=patch_size),
                               round(item["patchLeft"] * ART_SIZE[0] / SOURCE_STAGE[0]),
                               round(item["patchTop"] * ART_SIZE[1] / SOURCE_STAGE[1]),
                               *patch_size, alpha))
        index = len(visuals)
        visuals.append((first, len(layers) - first))
        visual_map[key] = index
        return index

    chapters = [(strings.add(chapter.get("title", chapter.get("id", ""))),
                 node_index[chapter["node"]],
                 strings.add(chapter.get("preview", ""))) for chapter in graph["chapters"]]
    chapter_names = {chapter.get("title", chapter.get("id", "")): i
                     for i, chapter in enumerate(graph["chapters"])}

    node_records = []
    for node_id in nodes:
        node = graph["nodes"][node_id]
        first_frame = len(frames)
        for chunk in node.get("chunks", []):
            rel = "src/common/story/" + chunk["file"].lstrip("/")
            path = source / rel
            if not path.is_file():
                die(f"missing story chunk: {rel}")
            rows = json.loads(path.read_text("utf-8"))
            if len(rows) != chunk["count"]:
                die(f"{node_id}: chunk {chunk['file']} has {len(rows)} rows, expected {chunk['count']}")
            background = ""
            sprites: list = []
            seen_art = False
            for row in rows:
                if row.get("kind") == "op":
                    op_frames += 1
                    frames.append((1, NONE, NONE, 0, 0, 0))
                    continue
                if "art" in row:
                    background = row["art"].get("background", "")
                    sprites = row["art"].get("sprites") or []
                    seen_art = True
                    speaker = row.get("speaker", "")
                    line = row.get("text", "")
                else:
                    if not seen_art and ("b" in row or "p" in row):
                        seen_art = True
                    background = row.get("b", background)
                    sprites = row.get("p", sprites)
                    speaker = row.get("s", "")
                    line = row.get("t", "")
                block_id, offset, length = text(line)
                frames.append((0, visual(background, sprites), block_id, offset,
                               length, strings.add(speaker)))
                total_text_frames += 1
        if len(frames) - first_frame != node["count"]:
            die(f"{node_id}: packed frame count mismatch")
        first_effect = len(effects)
        effect(node.get("effects", []))
        for ending in node.get("complete", []):
            effect([(ending, "=", 1)])
            if ending == "true":
                effect([("clear_true", "=", 1)])
        effect_count = len(effects) - first_effect
        first_next = len(edges)
        for item in node.get("nexts", []):
            edge(item)
        next_count = len(edges) - first_next
        first_choice = len(edges)
        for item in node.get("choices", []):
            edge(item)
        node_records.append((first_frame, node["count"], first_effect, effect_count,
                             first_next, next_count, first_choice, len(edges) - first_choice,
                             strings.add(node.get("title", "")),
                             chapter_names.get(node.get("chapter", ""), NONE),
                             strings.add(node_id),
                             strings.add(node.get("script", "") + ":" + node.get("label", ""))))
    if block:
        blocks.append(bytes(block))

    endings = [(strings.add(ending["name"]), var(ending["id"]),
                strings.add(ending.get("description", ""))) for ending in graph.get("endings", [])]

    gallery_groups = json.loads((source / "converted/gallery.json").read_text("utf-8"))
    gallery = []
    for group_index, group in enumerate(gallery_groups):
        for variant in group["variants"]:
            gallery.append((strings.add(variant["name"]),
                            media.image(variant["src"]), group_index))

    title_images = [media.image(f"/common/ui/title-bg{i}.jpg", crop=TITLE_CROP,
                                size=TITLE_BG_SIZE, opaque=True) for i in (1, 2, 3)]
    title_logo = media.image("/common/ui/title-logo.png", sprite=True, size=(51, 135))
    opening_report = media.add_opening()
    audio_report = media.add_audio(strings)

    variables = [(strings.add(name), 1 if name in persistent else 0) for name in var_names]

    # Header + tables. Field order is fixed by nine_format.h; strings follow the
    # compressed text blocks, which are patched after the tables exist.
    blob = bytearray(256)
    header = [PACK_VERSION, 0, 0, episode, title_s, sha_s, node_index[graph["start"]]]
    for table, stride in ((node_records, 12), (frames, 6),
                          ([(0, 0, len(block), crc32(block)) for block in blocks], 4),
                          (visuals, 2), (layers, 6), (variables, 2),
                          (conditions, 3), (effects, 3), (edges, 6),
                          (chapters, 3), (endings, 3), (gallery, 3)):
        header.extend((len(table), len(blob)))
        for row in table:
            blob.extend(p32(*row))
    header.extend((len(blob), len(strings.data)))
    blob.extend(strings.data)
    block_table = header[12]
    for i, block in enumerate(blocks):
        compressed = zlib.compress(block, 9)
        struct.pack_into("<4I", blob, block_table + i * 16, len(blob),
                         len(compressed), len(block), crc32(block))
        blob.extend(compressed)

    # Bind the pack to every source byte that contributed to it. Reading the
    # whole converted/source tree (not in-memory copies) makes the digest a real
    # snapshot check: a modified chunk, image or metadata file changes it.
    digest = hashlib.sha256()
    for directory in ("src/common", "converted"):
        root = source / directory
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            rel = path.relative_to(source).as_posix()
            payload = path.read_bytes()
            digest.update(rel.encode() + b"\0" + struct.pack("<Q", len(payload)) + payload)
    source_digest = digest.hexdigest()

    blob[:8] = b"NINESC1\0"
    header[1] = len(blob)
    struct.pack_into("<" + "I" * len(header), blob, 8, *header)
    struct.pack_into("<8I", blob, 140, *struct.unpack("<8I", bytes.fromhex(source_digest)[:32]))
    struct.pack_into("<I", blob, 16, crc32(blob))

    image_blob = media.serialize(title_images, title_logo)
    out.mkdir(parents=True, exist_ok=True)
    (out / "nine_script.bin").write_bytes(blob)
    (out / "nine_images.bin").write_bytes(image_blob)
    (out / "nine_symbols.txt").write_text(
        "".join(sorted(strings.chars - set("\r\n\t"))), encoding="utf-8")

    report = {
        "episode": "sorairo",
        "title": title_text,
        "sourceRepository": "https://github.com/xuanyide01/9-nine-rw5",
        "sourceCommit": source_sha,
        "sourceDigest": source_digest,
        "sourceDigestScope": "graph.js + converted graph + every story chunk + image/face/opening file + gallery/opening metadata + used UI media",
        "packVersion": PACK_VERSION,
        "scriptBytes": len(blob),
        "imageMediaBytes": len(image_blob),
        "totalPackBytes": len(blob) + len(image_blob),
        "nodes": len(nodes),
        "frames": len(frames),
        "textFrames": total_text_frames,
        "opFrames": op_frames,
        "textBytes": text_raw,
        "textBlocks": len(blocks),
        "maxTextBlock": max(map(len, blocks)),
        "variables": len(var_names),
        "persistentVariables": sorted(persistent),
        "visuals": len(visuals),
        "layers": len(layers),
        "images": len(media.images),
        "galleryVariants": len(gallery),
        "galleryGroups": len(gallery_groups),
        "chapters": len(chapters),
        "endings": len(endings),
        "opening": opening_report,
        "audio": audio_report,
        "jpegQuality": quality,
        "artSize": list(ART_SIZE),
        "titleBgCrop": TITLE_CROP,
        "scriptSha256": hashlib.sha256(blob).hexdigest(),
        "imageSha256": hashlib.sha256(image_blob).hexdigest(),
        "maxImageBlockRaw": max((image["w"] * min(8, image["h"])
                                 for image in media.images if image["kind"] == 1), default=0),
        "imageSources": media.meta,
    }
    (out / "nine_pack_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({key: value for key, value in report.items()
                      if key != "imageSources"}, ensure_ascii=False))
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--jpeg-quality", type=int, default=42)
    parser.add_argument("--op-fps", type=float, default=3)
    parser.add_argument("--audio-rate", type=int, default=12000,
                        choices=(8000, 12000, 16000))
    parser.add_argument("--expect-commit", default="")
    args = parser.parse_args()
    pack(args.source, args.out, args.jpeg_quality, args.op_fps,
         args.audio_rate, args.expect_commit)
    return 0


